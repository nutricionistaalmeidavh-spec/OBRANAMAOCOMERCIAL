import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {Script} from 'node:vm';
const root=join(dirname(fileURLToPath(import.meta.url)),'../public/guia');
const txt=path=>readFileSync(join(root,path),'utf8');
const fileNames=['01-10.json','11-20.json','21-30.json','31-40.json'];
const chapters=fileNames.map(x=>JSON.parse(txt('aulas/'+x)));
assert.ok(chapters.every(c=>Array.isArray(c)&&c.length===10),'4 chapters of 10 lessons');
const lessons=chapters.flat().sort((a,b)=>a.number-b.number);
assert.deepEqual(lessons.map(p=>p.number),Array.from({length:40},(_,i)=>i+1),'40 sequential lessons');
let words=0;
for(const p of lessons){
 assert.ok(typeof p.title==='string'&&p.title.length>=12,'title '+p.number);
 assert.ok(p.lead.length>=130,'real explanation '+p.number);
 assert.ok(p.steps.length>=5&&p.steps.every(s=>s.length>=55),'reproducible steps '+p.number);
 assert.ok(p.example.length>=50,'concrete example '+p.number);
 assert.ok(p.prompt.length>=100,'meaningful prompt '+p.number);
 assert.ok(p.checks.length>=3&&p.checks.every(s=>s.length>=15),'learning checks '+p.number);
 assert.ok(p.free.length>=38&&p.optional.length>=35&&p.caution.length>=45,'free/paid/risks '+p.number);
 assert.ok(Array.isArray(p.links)&&p.links.every(l=>/^https:\/\//.test(l.url)),'safe source URL '+p.number);
 assert.ok(p.status==='draft-for-review','release status is explicit '+p.number);
 words+=(p.lead+' '+p.steps.join(' ')+' '+p.example+' '+p.prompt+' '+p.checks.join(' ')).split(/\s+/).length;
}
assert.ok(words>=7400,'not merely PDF cover transcribed ('+words+' words)');
const chapterLabels=JSON.parse(txt('conteudo.json')).groups;
assert.equal(chapterLabels.length,7,'navigation groups remain unchanged');
const html=txt('index.html'),js=txt('guia.js'),css=txt('guia.css');
new Script(js,{filename:'guia.js'});
assert.match(js,/\/guia\/aulas\/01-10\.json/,'loads new lessons');
assert.match(js,/renderLesson\(page\)/,'renders structured lesson content');
assert.match(js,/page\.steps/,'steps actually rendered');
assert.match(js,/page\.prompt/,'prompts actually rendered');
assert.match(js,/page\.checks/,'checks actually rendered');
assert.match(js,/page\.free/,'free route explicitly rendered');
assert.match(js,/page\.optional/,'paid route explicitly rendered');
assert.match(js,/page\.caution/,'risks explicitly rendered');
assert.match(js,/n%2===0\?'light':'dark'/,'even light, odd dark');
assert.match(css,/\.reader\[data-theme="light"\] \.lesson-step/,'light background legibility');
assert.match(css,/\.lesson-code-pre/,'code blocks visible');
assert.match(html,/id="reader-theme-toggle"/,'theme switch');
assert.match(html,/href="#pagina-01"/,'starts from page 1');
assert.match(html,/PDF editorial · edição anterior/,'outdated PDF clearly labeled');
assert.match(html,/resource-pending/,'ZIP clearly pending');
assert.ok(!html.includes('href="/guia/kit.zip"'),'no fictional download');
assert.ok(!JSON.stringify(lessons[0]).includes('pipeline / app-preview'),'cover artifacts removed');
for(const n of [16,20,39])assert.ok(lessons[n-1].example.length>=200,'technical depth page '+n);
assert.ok(existsSync(join(root,'guia-completo.pdf')),'PDF old edition retained for users');
const pdf=readFileSync(join(root,'guia-completo.pdf'),'ascii');
assert.ok(pdf.startsWith('%PDF-1.4\n')&&/%%EOF\s*$/.test(pdf),'old PDF remains valid');
assert.equal((pdf.match(/\/Type \/Page\b/g)||[]).length,40,'old editorial PDF has 40 pages');
console.log('Guia editorial QA: 40 lessons with steps, prompts, examples and verification; '+words+' words, content v2 complete.');
